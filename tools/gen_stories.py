def cycle_check():
    seen, stack = set(), set()
    found = []

    def visit(sid, path):
        if sid in stack:
            found.append(u" → ".join(path + [sid]))
            return
        if sid in seen:
            return
        stack.add(sid)
        s = by_id(sid)
        for d in (s["deps"] if s else []):
            visit(d, path + [sid])
        stack.discard(sid)
        seen.add(sid)

    for s in STORIES:
        visit(s["id"], [])
    return u"تم الفحص على %d قصة" % len(STORIES) if not found \
        else u"**دوران مكتشف:** " + u"؛ ".join(found)


